// Bundles each server/entries/*.ts into a self-contained api/*.js for Vercel.
//
// Why bundle rather than let Vercel compile the TypeScript: the functions
// share the verdict engine with the web app, and that code is written for a
// bundler (extensionless imports, plain JSON imports). Node's own ES module
// loader accepts neither, so compiled file-by-file it would fail at runtime.
// A single bundled file per function has no imports left to resolve.
//
// The output is committed, and CI fails if it's out of date with its source.
import { readdirSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { build } from 'rolldown';

const entries = readdirSync('server/entries').filter((f) => f.endsWith('.ts'));

for (const file of entries) {
  const name = basename(file, '.ts');
  await build({
    input: `server/entries/${file}`,
    platform: 'node',
    external: [/^node:/],
    // Only waitUntil is used, but the package root also loads its cache and
    // OIDC clients (and a WebSocket library with them), ten times the size of
    // everything else here. Point straight at the one file instead.
    resolve: {
      alias: {
        '@vercel/functions': resolve('node_modules/@vercel/functions/wait-until.js'),
      },
    },
    logLevel: 'warn',
    output: {
      file: `api/${name}.js`,
      format: 'esm',
      // @vercel/functions lazy-loads a module; keep it all in the one file.
      codeSplitting: false,
      banner: `// GENERATED by scripts/build-api.mjs from server/entries/${file}. Do not edit; run \`npm run build:api\`.`,
    },
  });
  console.log(`api/${name}.js`);
}
